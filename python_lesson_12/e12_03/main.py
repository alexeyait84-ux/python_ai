import os
# Подключаем модуль os и его средства работы с путями.
path = os.path.join("files", "note.txt")
# Соединяем имя папки и имя файла по правилам системы.
print(path)
# Показываем собранный относительный путь.
print(os.path.isabs(path))
# Проверяем, является ли путь абсолютным.
print(os.path.exists(path))
# Проверяем, существует ли что-либо по этому пути.

