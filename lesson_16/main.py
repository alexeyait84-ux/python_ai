# Мы сравнили один вектор с одним вектором, поэтому получили одну оценку.
# Но функция возвращает ее внутри двумерной таблицы:
# Внешние скобки — таблица.
# Внутренние скобки — единственная строка.
# 0. — единственное число в этой строке. Это сокращенная запись 0.0.

# Здесь ноль означает, что выбранные нами векторы перпендикулярны.
# Эти числа мы задали вручную; функция сама не анализировала смысл каких-либо текстов.
