# Как достать число из результата
from sklearn.metrics.pairwise import cosine_similarity
# Подключаем сравнение векторов.
matrix = cosine_similarity([[1.0, 0.0]], [[0.8, 0.6]])
# Сравниваем один запрос с одним объектом.
row = matrix[0]
# Получаем первую строку таблицы результатов.
score = row[0]
# Получаем первое число из выбранной строки.
print(matrix.shape)
# Показываем форму таблицы результатов.
print(row)
# Печатаем строку с одной оценкой.
print(f"{score:.3f}")
