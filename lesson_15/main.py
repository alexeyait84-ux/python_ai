# Разделяем программу на функции
def get_text():
# Выделяем получение пользовательской строки в отдельную функцию.
    return input("Введите текст: ")
    # Передаем введенную строку вызывающему коду.
def normalize_text(text):
# Выделяем обработку переданного текста без чтения ввода.
    return text.strip().upper()
    # Возвращаем преобразованную строку без печати.
def show_result(text):
# Выделяем вывод уже готового результата.
    print("Результат:", text)
    # Показываем строку пользователю в одном согласованном формате.
def main():
# Собираем основной сценарий из вызовов небольших функций.
    text = get_text()
    # Получаем исходные данные и сохраняем их локально.
    result = normalize_text(text)
    # Передаем данные в обработку и получаем новую строку.
    show_result(result)
    # Передаем подготовленный результат функции вывода.
main()
