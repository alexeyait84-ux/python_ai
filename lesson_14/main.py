# Форма число измерений и тип элементов

import numpy as np
# Подключаем NumPy под общепринятым коротким именем.
matrix = np.array([[1, 2, 3], [4, 5, 6]], dtype=np.int64)
# Создаем две строки по три целых числа заданного типа.
print(matrix)
# Показываем массив в виде прямоугольной таблицы.
print(matrix.ndim)
# Получаем количество измерений массива.
print(matrix.shape)
# Получаем число элементов вдоль каждого измерения.
print(matrix.size)
# Получаем общее количество элементов во всем массиве.
print(matrix.dtype)
