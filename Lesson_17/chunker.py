def chunk_text(text, size=4, overlap=1):
# Описываем функцию; размеры считаем в словах, параметры ожидаем целыми.
    if size <= 0:
    # Проверяем, что в чанк разрешено поместить хотя бы одно слово.
        raise ValueError("size должен быть больше 0")
        # Сообщаем об ошибке до запуска цикла.
    if overlap < 0 or overlap >= size:
    # Проверяем, что перекрытие неотрицательно и меньше размера чанка.
        raise ValueError("Нужно 0 <= overlap < size")
        # Останавливаем вызов при недопустимом перекрытии.
    words = text.split()
    # Получаем список слов; для пустого текста получится пустой список.
    chunks = []
    # Готовим список готовых строк для результата.
    step = size - overlap
    # Вычисляем число слов, на которое будем сдвигать начало окна.
    start = 0
# Начинаем с первого слова с индексом ноль.
    while start < len(words):
    # Продолжаем, пока начало окна находится внутри списка.
        end = min(start + size, len(words))
        # Ограничиваем конец окна фактическим количеством слов.
        chunk = " ".join(words[start:end])
        # Собираем выбранные слова в одну строку через пробел.
        chunks.append(chunk)
        # Добавляем готовый чанк в список результатов.
        if end == len(words):
        # Проверяем, дошел ли текущий чанк до последнего слова.
            break
            # Завершаем цикл без дополнительного чанка из уже покрытого хвоста.
        start += step
        # Сдвигаем начало следующего окна на положительное число слов.
    return chunks
    # Передаем список чанков вызывающему коду после окончания цикла.