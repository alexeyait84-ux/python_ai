# Запросите возраст через input() и преобразуйте его в целое число.
# Возраст неотрицательный.
# Напечатайте ровно одну категорию: 0-17 -> Child; 18-65 -> Adult; от 66 -> Senior.
# Используйте if/elif/else.
# Контроль: 17 -> Child; 18 -> Adult; 65 -> Adult; 66 -> Senior.
# После четырех запусков объясните, почему число 65 относится ко второй группе.
age = int(input("Введите возраст: "))
if age > 0:
    if age <= 17:
        print("Вы - ребенок")
    elif age <= 65:
        print("Вы - взрослый")
    elif age >= 66:
        print("Вы - старик")
else:
    print("Возраст не должен быть отрицательным числом")