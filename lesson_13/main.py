import re
# Подключаем поиск всех совпадений.
text = "Order 123 failed, retry 456 times"
# Берем исходную строку из материалов урока.
numbers = re.findall(r"\d+", text)
# Находим все непересекающиеся последовательности цифр.
print(numbers)
# Выводим список строк, а не список целых чисел.
total = 0
# Подготавливаем числовой накопитель суммы.
for number in numbers:
# По очереди берем каждую найденную строку.
    total = total + int(number)
    # Преобразуем строку в целое число и добавляем к сумме.
print("Сумма:", total)
